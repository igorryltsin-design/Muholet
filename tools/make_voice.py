def main() -> None:
    if not MODEL_PATH.exists():
        print(f"модель не найдена: {MODEL_PATH}")
        sys.exit(1)
    args = sys.argv[1:]
    voice_filter = None
    if args and args[0] in VOICES:
        voice_filter = args[0]
        args = args[1:]
    # без аргументов — каждый голос записывает свой набор ключей; с аргументами —
    # ключи должны существовать во всех записываемых голосах
    if args:
        scope = [voice_filter] if voice_filter else list(VOICES)
        unknown = [k for k in args if any(k not in VOICES[v][1] for v in scope)]
        if unknown:
            print(f"неизвестные ключи: {unknown}; есть: {sorted(set().union(*(set(VOICES[v][1]) for v in scope)))}")
            sys.exit(1)

    device = "cpu"
    model = torch.package.PackageImporter(str(MODEL_PATH)).load_pickle("tts_models", "model", map_location=device)

    for voice_dir, (speaker, phrases) in VOICES.items():
        if voice_filter and voice_dir != voice_filter:
            continue
        for key in args or phrases:
            for i, text in enumerate(phrases[key]):
                out = OUT_DIR / voice_dir / f"{key}_{i}.wav"
                out.parent.mkdir(parents=True, exist_ok=True)
                audio = model.apply_tts(
                    text=text, speaker=speaker, sample_rate=SAMPLE_RATE
                ).numpy()
                pcm = (audio * 32767).astype("int16")
                with wave.open(str(out), "wb") as w:
                    w.setnchannels(1)
                    w.setsampwidth(2)
                    w.setframerate(SAMPLE_RATE)
                    w.writeframes(pcm.tobytes())
                print(f"{voice_dir}/{key}_{i}.wav  {len(audio) / SAMPLE_RATE:.1f} с  «{text}»")
    print("готово")


if __name__ == "__main__":
    main()

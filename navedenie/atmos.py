"""Стандартная атмосфера ICAO (Doc 7488) / US Standard Atmosphere 1976.

Плотность воздуха ρ(H) по ГЕОПОТЕНЦИАЛЬНОЙ высоте в слоях 0…84.852 км:

  градиентный слой (L = dT/dH ≠ 0):
      T(H) = T_b + L·(H − H_b),
      ρ(H) = ρ_b · (T/T_b)^(−g0/(R·L) − 1)
  изотермический слой (L = 0):
      ρ(H) = ρ_b · exp(−g0·(H − H_b) / (R·T_b))

Константы: g0 = 9.80665 м/с² (стандартное ускорение свободного падения),
R = 287.05287 Дж/(кг·К) (удельная газовая постоянная сухого воздуха).
Опорные точки слоёв (высота, км; T, K; L, K/км) — таблица US1976:
  0 / 11 / 20 / 32 / 47 / 51 / 71
  288.150 / 216.650 / 216.650 / 228.650 / 270.650 / 270.650 / 214.650
  −6.5 / 0 / +1.0 / +2.8 / 0 / −2.8 / 0
Диапазон модели: 0…84.852 км (последний слой 71…84.852 км изотермический,
T = 214.65 K); выше 84.852 км плотность заморожена — мезосферные слои со
степеньными градиентами стенду не нужны.

Опорные плотности ρ_b вычисляются от ρ(0) = 1.225 кг/м³ теми же формулами
(самосогласованно; расхождение с печатными таблицами US1976 <0.1%, например
ρ(11 км) = 0.363916 кг/м³ — табличное значение совпадает точно).

Честные упрощения (зафиксированы в docs/model_assumptions.md):
  - геопотенциальная высота приравнивается геометрической (расхождение ~0.3 %
    на 20 км);
  - состав воздуха постоянен (сухой воздух, M не влияет на R);
  - вне диапазона 0…84.852 км — константа на границе (физичной модели выше
    термосферы в стенде нет).
"""

from __future__ import annotations

import math

G0 = 9.80665          # стандартное ускорение свободного падения, м/с²
R_AIR = 287.05287     # удельная газовая постоянная сухого воздуха, Дж/(кг·К)
RHO_SEA_LEVEL = 1.225  # плотность на уровне моря, кг/м³ (определение стандарта)
GAMMA_AIR = 1.4       # показатель адиабаты воздуха (сухой воздух, демонстрационно постоянен)

# (H_b, м; T_b, K; L, K/м) — опорные точки слоёв US1976 по геопотенциальной высоте
_LAYERS: tuple[tuple[float, float, float], ...] = (
    (0.0, 288.150, -0.0065),
    (11000.0, 216.650, 0.0),
    (20000.0, 216.650, 0.001),
    (32000.0, 228.650, 0.0028),
    (47000.0, 270.650, 0.0),
    (51000.0, 270.650, -0.0028),
    (71000.0, 214.650, 0.0),
)
H_MIN_M = _LAYERS[0][0]
H_MAX_M = 84852.0  # верх границы последнего слоя таблицы US1976 (84.852 км)


def _clamp(h_m: float) -> float:
    return min(max(float(h_m), H_MIN_M), H_MAX_M)


def _layer_index(h_m: float) -> int:
    i = 0
    for j, (hb, _t, _l) in enumerate(_LAYERS):
        if h_m >= hb:
            i = j
    return i


def air_temperature(h_m: float) -> float:
    """Температура стандартной атмосферы, K, на геопотенциальной высоте h_m, м."""
    h = _clamp(h_m)
    hb, tb, l = _LAYERS[_layer_index(h)]
    return tb + l * (h - hb)


def _density_from_base(h: float, hb: float, tb: float, l: float, rb: float) -> float:
    dh = h - hb
    if l == 0.0:
        return rb * math.exp(-G0 * dh / (R_AIR * tb))
    t = tb + l * dh
    return rb * (t / tb) ** (-G0 / (R_AIR * l) - 1.0)


def _build_bases() -> tuple[float, ...]:
    bases = [RHO_SEA_LEVEL]
    for i in range(1, len(_LAYERS)):
        hb_prev, tb_prev, l_prev = _LAYERS[i - 1]
        hb_new = _LAYERS[i][0]
        bases.append(_density_from_base(hb_new, hb_prev, tb_prev, l_prev, bases[-1]))
    return tuple(bases)


_RHO_BASE = _build_bases()


def air_density(h_m: float) -> float:
    """Плотность воздуха стандартной атмосферы, кг/м³, на геопотенциальной
    высоте h_m, м (вне диапазона 0…84.852 км — значение на границе)."""
    h = _clamp(h_m)
    i = _layer_index(h)
    hb, tb, l = _LAYERS[i]
    return _density_from_base(h, hb, tb, l, _RHO_BASE[i])


def speed_of_sound(h_m: float) -> float:
    """Локальная скорость звука стандартной атмосферы a(H) = √(γ·R·T(H)), м/с.
    Табличные опоры US1976: a(0) = 340.294, a(11 км) = 299.466 м/с."""
    return math.sqrt(GAMMA_AIR * R_AIR * air_temperature(h_m))

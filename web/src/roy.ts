/** Детерминированный вариант реплики: тот же прогон — та же интонация. */
export function royVariant(key: RoyKey, gen: number): number {
  const h = (gen * 31 + ROY_KEYS.indexOf(key) * 17 + 5) >>> 0
  return h % ROY_PHRASES[key].length
}

export function royLine(key: RoyKey, gen: number): { key: RoyKey; variant: number; text: string } {
  const variant = royVariant(key, gen)
  return { key, variant, text: ROY_PHRASES[key][variant] }
}
